using System;
using System.Collections.Generic;
using System.Text;

namespace Subjects
{
    public class Math
    {
        public double sum(int num1, int num2)
        {
            return num1 + num2;
        }
        public double mult(int num1, int num2)
        {
            return num1 * num2;
        }
        public double subtraction(int num1, int num2)
        {
            return num1 - num2;
        }
        public double division(int num1, int num2)
        {        
            return num1 / num2;
        }
    }
}
